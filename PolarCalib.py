def resize_to_fit_screen(img, max_w=1280, max_h=720, only_shrink=True):
    h, w = img.shape[:2]
    scale = min(max_w / float(w), max_h / float(h))
    if only_shrink and scale >= 1.0:
        return img, 1.0
    nw = max(1, int(round(w * scale)))
    nh = max(1, int(round(h * scale)))
    interp = cv2.INTER_AREA if scale < 1.0 else cv2.INTER_LINEAR
    return cv2.resize(img, (nw, nh), interpolation=interp), scale


def polar_rgba_to_gray(rgba):
    """Average all 4 polarization channels into a single uint8 grayscale image."""
    return np.mean(rgba.astype(np.float32), axis=2).astype(np.uint8)


def load_robot_pose(csv_path):
    """
    Parse robot_pose.csv (single data row).
    Columns: J1,J2,J3,J4,J5,J6,X,Y,Z,Rx,Ry,Rz

    IMPORTANT – Doosan H2515 / CS-01 controller:
      X,Y,Z  : TCP position in millimetres
      Rx,Ry,Rz : ZYZ Euler angles in degrees (NOT roll-pitch-yaw)
                 Rx = rz1 (first  Z), Ry = ry (Y), Rz = rz2 (second Z)

    Returns a dict with float values keyed by the CSV column names.
    """
    with open(csv_path, newline='') as f:
        reader = csv.DictReader(f)
        row = next(reader)
    return {k.strip(): float(v) for k, v in row.items()}


def load_camera_csv(csv_path):
    """
    Parse camera.csv (timestamp / frameID table).
    Returns list of dicts.
    """
    entries = []
    with open(csv_path, newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            entries.append({k.strip(): v.strip() for k, v in row.items()})
    return entries


def save_stereolabs_calib(out_path, width, height, intrinsic_matrix, dist_coeffs,
                          camera_id=0, camera_no=0, date="", description="",
                          scale_unit=1.0,
                          comment_camera="Polarization Camera",
                          comment_source="Generated by PolarCalib.py"):
    I = np.asarray(intrinsic_matrix, dtype=float).reshape(3, 3)
    D = np.asarray(dist_coeffs, dtype=float).reshape(-1)
    if D.size < 5:
        D = np.pad(D, (0, 5 - D.size), mode="constant")
    D = D[:5]

    lines = [
        f"%Calibration File v 1.0.3 - Matlab Load() compatible, "
        f"https://support.stereolabs.com/hc/en-us/articles/360007497173-What-is-the-calibration-file- "
        f"Scale Unit: {scale_unit}  - {comment_camera} - {comment_source}",
        f"%CameraID={camera_id}",
        f"%CameraNo={camera_no}",
        "%Date=" + (date or ""),
        "%Width", str(int(width)),
        "%Height", str(int(height)),
        "%Description=" + (description or ""),
        "%Intrinsics I[1,1], I[1,2], I[1,3], I[2,1], I[2,2], I[2,3], I[3,1], I[3,2] I[3,3]",
        "%I",
    ]
    for r in range(3):
        for c in range(3):
            lines.append(f"{I[r,c]:.8f}")
    lines += ["%Distortion D[1], D[2], D[3], D[4] D[5]", "%D"]
    for v in D:
        lines.append(f"{v:.8f}")
    lines += [
        "%Translation T.X, T.Y, T.Z", "%T", "0", "0", "0",
        "%Rotation Vector (Rodrigues) R.X, R.Y, R.Z", "%R", "0", "0", "0",
    ]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


